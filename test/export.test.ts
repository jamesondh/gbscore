import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { compile } from '../src/core/compile.ts';
import type { DriverSong } from '../src/core/driver.ts';
import { cName, exportGbdk } from '../src/core/export.ts';
import { importUge } from '../src/core/import.ts';
import type { Song } from '../src/core/schema.ts';
import { demoSong, fixture, readsBack } from './songs.ts';

function compiled(song: Song): DriverSong {
  const c = compile(song);
  if (!c.ok) throw new Error(c.errors.map((e) => e.message).join('\n'));
  return c.data;
}

const haltBugUge = () => compiled(importUge(readFileSync(fixture('halt_bug.uge'))).song);

describe('export --gbdk', () => {
  it("HALT Bug's .uge reads back as the compiled song", () => readsBack(haltBugUge()));
  it('the demo song reads back as the compiled song', () => readsBack(compiled(demoSong())));

  it("writes HALT Bug's .uge as uge2source does, apart from the pattern numbers and the comment", () => {
    const ours = exportGbdk(haltBugUge(), { name: 'song', bank: 255 }).split('\n');
    const theirs = readFileSync(fixture('halt_bug.uge2source.c'), 'utf8').split('\n');
    const strip = (lines: string[]) =>
      lines.filter((l) => !l.startsWith('//') && l !== '').map((l) => l.replace(/\bP\d+\b/g, 'P'));
    expect(strip(ours)).toEqual(strip(theirs));
  });

  it('names the song and its bank for CrossZGB', () => {
    const text = exportGbdk(haltBugUge(), { name: 'halt_bug_uge', bank: 7, source: 'halt_bug.gbscore.json' });
    expect(text.split('\n')[0]).toBe("// Generated by gbscore from halt_bug.gbscore.json. Don't edit; edit the song instead.");
    expect(text).toContain('#pragma bank 7\n');
    expect(text).toContain('const void __at(7) __bank_halt_bug_uge;\nconst hUGESong_t halt_bug_uge = {6, 6, 6, 6, 26,');
    expect(cName('res/music/halt_bug.gbscore.json')).toBe('halt_bug_uge');
    expect(cName('halt-bug.gbscore.json')).toEqual({ error: "halt-bug isn't a C name; rename the file or pass --name" });
  });
});
