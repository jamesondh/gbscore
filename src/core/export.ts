import type { DriverSong, Instrument, Row } from './driver.ts';
import { NO_NOTE } from './notes.ts';

// The song as GBDK C, the way uge2source writes it (hUGETracker's RenderSongToGBDKC): patterns as DN() rows,
// tables, order lists, instrument structs, waves, and the hUGESong_t, in one file the game compiles and links.

const NOTE_NAMES = ['C_', 'Cs', 'D_', 'Ds', 'E_', 'F_', 'Fs', 'G_', 'Gs', 'A_', 'As', 'B_'];
const noteMacro = (n: number) => `${NOTE_NAMES[n % 12]}${Math.floor(n / 12) + 3}`;
const fx = (r: Row) => `0x${((r.code << 8) | r.param).toString(16).toUpperCase().padStart(3, '0')}`;

const KINDS = [
  ['duty', 'itSquare', 'hUGEDutyInstr_t'],
  ['wave', 'itWave', 'hUGEWaveInstr_t'],
  ['noise', 'itNoise', 'hUGENoiseInstr_t'],
] as const;

export interface ExportOptions {
  /** The hUGESong_t's C name. CrossZGB's DECLARE_MUSIC(x) and PlayMusic(x) expect `x_uge`. */
  name: string;
  /** The ROM bank; 255 lets GBDK's bankpack choose. */
  bank: number;
  /** The song file, named in the header comment. */
  source?: string;
}

/** The C name for a song file: `tune.gbscore.json` becomes `tune_uge`, or a message if the name won't do. */
export function cName(file: string): string | { error: string } {
  const base = file.replace(/^.*[\\/]/, '').replace(/\.gbscore\.json$/i, '');
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(base)) {
    return { error: `${base} isn't a C name; rename the file or pass --name` };
  }
  return `${base}_uge`;
}

export function exportGbdk(s: DriverSong, options: ExportOptions): string {
  const out: string[] = [];
  out.push(`// Generated by gbscore${options.source ? ` from ${options.source}` : ''}. Don't edit; edit the song instead.`);
  out.push(`#pragma bank ${options.bank}`, '', '#include "hUGEDriver.h"', '#include <stddef.h>', '');

  s.patterns.forEach((p, i) => {
    out.push(`static const unsigned char P${i}[] = {`);
    for (const r of p) out.push(`    DN(${r.note === NO_NOTE ? '___' : noteMacro(r.note)},${r.inst},${fx(r)}),`);
    out.push('};');
  });
  out.push('');

  for (const [kind, prefix] of KINDS) {
    s[kind].forEach((inst, i) => {
      if (!inst.table) return;
      out.push(`static const unsigned char ${prefix}SP${i + 1}[] = {`);
      for (const r of inst.table) out.push(`    DN(${r.note === NO_NOTE ? '___' : r.note},${r.inst},${fx(r)}),`);
      out.push('};');
    });
  }

  s.orders.forEach((o, ch) => out.push(`static const unsigned char* const order${ch + 1}[] = {${o.map((p) => `P${p}`).join(',')}};`));
  out.push('');

  for (const [kind, prefix, type] of KINDS) {
    const bank = s[kind];
    if (!bank.length) {
      out.push(`static const ${type}* ${kind}_instruments = NULL;`, '');
      continue;
    }
    out.push(`static const ${type} ${kind}_instruments[] = {`);
    bank.forEach((inst: Instrument, i) => {
      const f = inst.fields;
      const table = inst.table ? `${prefix}SP${i + 1}` : '0';
      const fields = kind === 'noise' ? [f[0], table, f[1], f[2], f[3]] : [f[0], f[1], f[2], table, f[3]];
      out.push(`    {${fields.join(',')}},`);
    });
    out.push('};');
  }
  out.push('');

  if (s.waves.length) {
    out.push('static const unsigned char waves[] = {');
    for (const w of s.waves) out.push(`    ${w.join(',')},`);
    out.push('};');
  } else {
    out.push('static const unsigned char* waves = NULL;');
  }
  out.push('');

  out.push(`const void __at(${options.bank}) __bank_${options.name};`);
  const [t1, t2, t3, t4] = s.groove;
  out.push(
    `const hUGESong_t ${options.name} = {${t1}, ${t2}, ${t3}, ${t4}, ${s.orders[0]!.length * 2}, order1, order2, ` +
      'order3,order4, duty_instruments, wave_instruments, noise_instruments, NULL, waves};', // spaced as uge2source
  );
  return out.join('\n') + '\n';
}
